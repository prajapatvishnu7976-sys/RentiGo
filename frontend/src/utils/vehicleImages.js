export const getVehicleFallback = (type, brand, model, category) => {
  if (!brand && !model) {
    return type === "2W" ? "/vehicles/bikes/splendor.png" : "/vehicles/cars/swift.png";
  }

  // 1. Try EXACT match "Brand Model"
  const exactKey = `${brand} ${model}`;
  if (BRAND_IMAGES[exactKey]) return BRAND_IMAGES[exactKey];

  // 2. Try partial match
  const searchKey = `${brand} ${model}`.toLowerCase();
  const partialMatch = Object.keys(BRAND_IMAGES).find((k) =>
    k.toLowerCase().includes(searchKey) || searchKey.includes(k.toLowerCase())
  );
  if (partialMatch) return BRAND_IMAGES[partialMatch];

  // 3. Model only match
  if (model) {
    const modelMatch = Object.keys(BRAND_IMAGES).find((k) =>
      k.toLowerCase().includes(model.toLowerCase())
    );
    if (modelMatch) return BRAND_IMAGES[modelMatch];
  }

  // 4. Type-based fallback (last resort)
  if (type === "2W") {
    const cat = (category || model || "").toLowerCase();
    if (cat.includes("scooter") || cat.includes("activa") || cat.includes("jupiter") || cat.includes("dio") || cat.includes("access")) {
      return "/vehicles/scooters/activa.png";
    }
    if (cat.includes("classic") || cat.includes("bullet") || cat.includes("meteor")) {
      return "/vehicles/bikes/classic350.png";
    }
    if (cat.includes("r15") || cat.includes("sport") || cat.includes("rc")) {
      return "/vehicles/bikes/r15.png";
    }
    if (cat.includes("pulsar")) return "/vehicles/bikes/pulsar150.png";
    if (cat.includes("apache")) return "/vehicles/bikes/apache160.png";
    return "/vehicles/bikes/splendor.png";
  }

  // 4W - Cars
  const cat = (category || model || "").toLowerCase();
  if (cat.includes("thar")) return "/vehicles/cars/thar.png";
  if (cat.includes("scorpio")) return "/vehicles/cars/scorpio.png";
  if (cat.includes("fortuner")) return "/vehicles/cars/fortuner.png";
  if (cat.includes("xuv")) return "/vehicles/cars/xuv700.png";
  if (cat.includes("creta")) return "/vehicles/cars/creta.png";
  if (cat.includes("nexon")) return "/vehicles/cars/nexon.png";
  if (cat.includes("brezza")) return "/vehicles/cars/brezza.png";
  if (cat.includes("bolero")) return "/vehicles/cars/bolero.png";
  if (cat.includes("harrier")) return "/vehicles/cars/harrier.png";
  if (cat.includes("safari")) return "/vehicles/cars/safari.png";
  if (cat.includes("innova")) return "/vehicles/cars/innova.png";
  if (cat.includes("ertiga")) return "/vehicles/cars/ertiga.png";
  if (cat.includes("seltos")) return "/vehicles/cars/seltos.png";
  if (cat.includes("sonet")) return "/vehicles/cars/sonet.png";
  if (cat.includes("suv")) return "/vehicles/extra/suv.jpg";
  if (cat.includes("taxi")) return "/vehicles/extra/taxi.png";

  // Sedan/Hatchback default
  return "/vehicles/cars/swift.png";
};

